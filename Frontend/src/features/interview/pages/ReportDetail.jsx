import React, { useEffect, useState } from "react";
import { useParams, Link } from "react-router";
import { getReportById } from "../../interview/services/interview.api";
import "./reportDetail.scss";

const ReportDetail = () => {
  const { id } = useParams();
  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [activeTab, setActiveTab] = useState("overview");

  useEffect(() => {
    const fetchReport = async () => {
      try {
        const data = await getReportById(id);
        setReport(data.report);
      } catch (err) {
        setError(err.message);
      } finally {
        setLoading(false);
      }
    };
    fetchReport();
  }, [id]);

  if (loading) {
    return (
      <main className="report-detail-page">
        <div className="loading">Loading report...</div>
      </main>
    );
  }

  if (error || !report) {
    return (
      <main className="report-detail-page">
        <div className="error-state">
          <h2>Report not found</h2>
          <p>{error || "This report does not exist or you don't have access."}</p>
          <Link to="/reports" className="button primary-button">
            Back to Reports
          </Link>
        </div>
      </main>
    );
  }

  const tabs = [
    { key: "overview", label: "Overview" },
    { key: "technical", label: "Technical Q&A" },
    { key: "behavioral", label: "Behavioral Q&A" },
    { key: "skillgaps", label: "Skill Gaps" },
    { key: "plan", label: "Prep Plan" },
  ];

  return (
    <main className="report-detail-page">
      <div className="report-detail-container">
        <Link to="/reports" className="back-link">
          ← Back to Reports
        </Link>

        {report.isDemo && (
          <div className="demo-notice">
            📋 This is a <strong>Sample Demo Report</strong> — pre-loaded for
            demonstration purposes. It was not generated by a live AI call.
          </div>
        )}

        <div className="report-hero">
          <div
            className={`score-circle ${
              report.overallScore >= 75
                ? "high"
                : report.overallScore >= 50
                ? "mid"
                : "low"
            }`}
          >
            <span className="score-value">{report.overallScore}</span>
            <span className="score-label">Match Score</span>
          </div>
          <div className="hero-info">
            <h1>Interview Preparation Report</h1>
            <p className="hero-date">
              Generated on{" "}
              {new Date(report.createdAt).toLocaleDateString("en-IN", {
                day: "numeric",
                month: "long",
                year: "numeric",
              })}
            </p>
          </div>
        </div>

        <div className="tabs">
          {tabs.map((tab) => (
            <button
              key={tab.key}
              className={`tab ${activeTab === tab.key ? "active" : ""}`}
              onClick={() => setActiveTab(tab.key)}
            >
              {tab.label}
            </button>
          ))}
        </div>

        <div className="tab-content">
          {activeTab === "overview" && (
            <div className="overview-tab">
              <div className="section">
                <h3>Job Description</h3>
                <pre className="preformatted">{report.jobDescription}</pre>
              </div>
              <div className="section">
                <h3>Self Description</h3>
                <p>{report.selfDescription}</p>
              </div>
              <div className="section">
                <h3>Resume Text (Extracted)</h3>
                <pre className="preformatted">{report.resumeText}</pre>
              </div>
            </div>
          )}

          {activeTab === "technical" && (
            <div className="qna-tab">
              <h3>Technical Interview Questions</h3>
              {report.technicalQnA && report.technicalQnA.length > 0 ? (
                report.technicalQnA.map((item, idx) => (
                  <div className="qna-card" key={idx}>
                    <div className="q-number">Q{idx + 1}</div>
                    <div className="q-content">
                      <h4 className="question">{item.question}</h4>
                      <div className="intention">
                        <strong>Why this is asked:</strong> {item.intention}
                      </div>
                      <div className="answer">
                        <strong>How to answer:</strong>
                        <p>{item.answer}</p>
                      </div>
                    </div>
                  </div>
                ))
              ) : (
                <p className="empty">No technical questions available.</p>
              )}
            </div>
          )}

          {activeTab === "behavioral" && (
            <div className="qna-tab">
              <h3>Behavioral Interview Questions (STAR Format)</h3>
              {report.behavioralQnA && report.behavioralQnA.length > 0 ? (
                report.behavioralQnA.map((item, idx) => (
                  <div className="qna-card" key={idx}>
                    <div className="q-number">Q{idx + 1}</div>
                    <div className="q-content">
                      <h4 className="question">{item.question}</h4>
                      <div className="intention">
                        <strong>Why this is asked:</strong> {item.intention}
                      </div>
                      <div className="answer">
                        <strong>How to answer:</strong>
                        <p>{item.answer}</p>
                      </div>
                    </div>
                  </div>
                ))
              ) : (
                <p className="empty">No behavioral questions available.</p>
              )}
            </div>
          )}

          {activeTab === "skillgaps" && (
            <div className="skillgaps-tab">
              <h3>Skill Gap Analysis</h3>
              {report.skillGaps && report.skillGaps.length > 0 ? (
                <div className="gaps-grid">
                  {report.skillGaps.map((gap, idx) => (
                    <div className={`gap-card ${gap.severity}`} key={idx}>
                      <span className="gap-skill">{gap.skill}</span>
                      <span className={`severity-badge ${gap.severity}`}>
                        {gap.severity}
                      </span>
                    </div>
                  ))}
                </div>
              ) : (
                <p className="empty">No skill gaps identified. Great job!</p>
              )}
            </div>
          )}

          {activeTab === "plan" && (
            <div className="plan-tab">
              <h3>Personalized Preparation Plan</h3>
              {report.preparationPlan && report.preparationPlan.length > 0 ? (
                <div className="plan-timeline">
                  {report.preparationPlan.map((day, idx) => (
                    <div className="plan-day" key={idx}>
                      <div className="day-marker">
                        <span className="day-num">Day {day.day}</span>
                      </div>
                      <div className="day-content">
                        <h4>{day.focus}</h4>
                        <ul>
                          {day.tasks.map((task, tIdx) => (
                            <li key={tIdx}>{task}</li>
                          ))}
                        </ul>
                      </div>
                    </div>
                  ))}
                </div>
              ) : (
                <p className="empty">No preparation plan available.</p>
              )}
            </div>
          )}
        </div>
      </div>
    </main>
  );
};

export default ReportDetail;
